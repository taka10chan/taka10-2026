// --- 材質は色ごとに使い回す ---------------------------------
const MAT = new Map();
function mat(hex) {
  let m = MAT.get(hex);
  if (!m) { m = new THREE.MeshLambertMaterial({ color: hex }); MAT.set(hex, m); }
  return m;
}

