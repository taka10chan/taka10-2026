// --- 小さな道具 ----------------------------------------------
/** 箱をひとつ足す。回転は度で指定。 */
function box(g, w, h, d, x, y, z, hex, rx = 0, ry = 0, rz = 0) {
  const m = new THREE.Mesh(new THREE.BoxGeometry(w, h, d), mat(hex));
  m.position.set(x, y, z);
  if (rx || ry || rz) m.rotation.set(rx * Math.PI / 180, ry * Math.PI / 180, rz * Math.PI / 180);
  g.add(m);
  return m;
}

/**
 * 円柱をひとつ足す。rA / rB を変えると先細りになる。
 * axis 'z' のときは rA が後ろ側、rB が前側の半径。
 */
function cyl(g, rA, rB, len, x, y, z, hex, axis = 'z', seg = 12) {
  const m = new THREE.Mesh(new THREE.CylinderGeometry(rA, rB, len, seg), mat(hex));
  m.position.set(x, y, z);
  if (axis === 'z') m.rotation.x = Math.PI / 2;
  else if (axis === 'x') m.rotation.z = Math.PI / 2;
  g.add(m);
  return m;
}

/** 円筒のまわりに細い箱を並べる。ローレット（滑り止めの刻み）の表現。 */
function knurl(g, count, radius, w, h, d, x, y, z, hex) {
  for (let i = 0; i < count; i++) {
    const a = (i / count) * Math.PI * 2;
    box(g, w, h, d,
        x + Math.sin(a) * radius, y + Math.cos(a) * radius, z,
        hex, 0, 0, -a * 180 / Math.PI);
  }
}

