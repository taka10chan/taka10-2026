// グロック18C（マシンピストル）の3Dモデル。
//
// 実物は全長 185mm・高さ 138mm。1ユニット = 1スタッド = 約 0.28m なので、
// 全長 0.66 ユニット・高さ 0.49 ユニット（延長弾倉を除く）で作ります。
//
// 向き … 銃身は -Z。+Y が上、+X が撃つ人の右手側。
// 原点 … 手の水かき（バックストラップ上端、ビーバーテイルの真下）。
//         ここを持ち手の基準にして、全部がここからぶら下がります。
//
// 18C の見分けどころ:
//   ・スライド上面の四つの穴（コンペンセイター）
//   ・スライド後部右のセレクター（単発／連射の切り替え）
//   ・グリップから長く突き出た 33 連マガジン

import * as THREE from '../../lib/three.module.js';

// ── 色。真っ黒一色だと影絵になってしまうので、近い黒と灰を何種類か使い分けます ──
const MAT = new Map();
function mat(hex) {
  let m = MAT.get(hex);
  if (!m) { m = new THREE.MeshLambertMaterial({ color: hex }); MAT.set(hex, m); }
  return m;
}

const POLY     = 0x1b1917;   // フレームの樹脂。ほんの少し暖かい黒
const POLY_HI  = 0x272320;   // 樹脂の当たっている面／滑り止めの粒
const SLIDE    = 0x2b2f36;   // スライドの鉄。冷たい濃灰
const SLIDE_HI = 0x3b414a;   // スライドの照り返し
const SLIDE_LO = 0x1f2329;   // スライドの陰の面
const SHADOW   = 0x07080a;   // 穴やすき間の底
const STEEL    = 0x646a72;   // 引き金やレバーの、擦れて光った鋼
const STEEL_D  = 0x474d55;   // 同じ鋼の陰
const BARREL   = 0x4e535b;   // 銃身。スライドより少し明るい
const MAGBODY  = 0x101216;   // 弾倉の本体
const MAGEDGE  = 0x0c0e11;   // 弾倉の稜線
const WHITE    = 0xe9e7e0;   // 照準の白い点

// ── 部品を置く小道具 ──────────────────────────────────────
/** 箱をひとつ。回転は度で指定。 */
function box(g, w, h, d, x, y, z, hex, rx, ry, rz) {
  const m = new THREE.Mesh(new THREE.BoxGeometry(w, h, d), mat(hex));
  m.position.set(x, y, z);
  if (rx || ry || rz) {
    m.rotation.set((rx || 0) * Math.PI / 180, (ry || 0) * Math.PI / 180, (rz || 0) * Math.PI / 180);
  }
  g.add(m);
  return m;
}

/** 円柱をひとつ。axis は伸びる向き。 */
function cyl(g, r, len, x, y, z, hex, axis, seg) {
  const m = new THREE.Mesh(new THREE.CylinderGeometry(r, r, len, seg || 10), mat(hex));
  m.position.set(x, y, z);
  if (axis === 'x') m.rotation.z = Math.PI / 2;
  else if (axis !== 'y') m.rotation.x = Math.PI / 2;   // 既定は Z 方向
  g.add(m);
  return m;
}

// グリップは 18 度後ろに寝ています。マガジンもそれに沿います。
// gbox() は「傾いたグリップの中での座標」で置ける箱。原点まわりに回します。
const RAKE = 18;
const CR = Math.cos(RAKE * Math.PI / 180);
const SR = Math.sin(RAKE * Math.PI / 180);
function gbox(g, w, h, d, gx, gy, gz, hex) {
  const m = new THREE.Mesh(new THREE.BoxGeometry(w, h, d), mat(hex));
  m.position.set(gx, gy * CR - gz * SR, gy * SR + gz * CR);
  m.rotation.x = RAKE * Math.PI / 180;
  g.add(m);
  return m;
}

// ── 主な高さ・位置。ここを直せば全体の寸法が動きます ──────────
const SIGHT_Y     = 0.117;   // 照星と照門の頭がそろう高さ＝狙う線
const SLIDE_BOT   = 0.012;   // スライドの下端
const SLIDE_TOP   = 0.096;   // スライドの上端（平ら）
const SLIDE_BACK  = -0.045;  // スライドの後ろ端
const SLIDE_FRONT = -0.665;  // スライドの前端＝銃口
const SLIDE_MIDY  = (SLIDE_BOT + SLIDE_TOP) / 2;
const SLIDE_LEN   = SLIDE_BACK - SLIDE_FRONT;
const SLIDE_MIDZ  = (SLIDE_BACK + SLIDE_FRONT) / 2;
const BORE_Y      = 0.056;   // 銃身の芯の高さ
const SPRING_Y    = 0.026;   // 復座ばねの芯の高さ

export function build() {
  const g = new THREE.Group();

  // ── スライド本体。角ばった箱で、横は平らな面（スラブサイド） ──
  box(g, 0.091, SLIDE_TOP - SLIDE_BOT, SLIDE_LEN, 0, SLIDE_MIDY, SLIDE_MIDZ, SLIDE);
  box(g, 0.085, 0.008, SLIDE_LEN - 0.010, 0, SLIDE_TOP - 0.003, SLIDE_MIDZ, SLIDE_HI);   // 平らな上面
  box(g, 0.004, 0.058, SLIDE_LEN - 0.060, -0.0462, 0.056, SLIDE_MIDZ - 0.010, SLIDE_LO); // 左の平面
  box(g, 0.004, 0.058, SLIDE_LEN - 0.060,  0.0462, 0.056, SLIDE_MIDZ - 0.010, SLIDE_LO); // 右の平面
  box(g, 0.007, 0.014, SLIDE_LEN, -0.0455, SLIDE_BOT + 0.006, SLIDE_MIDZ, SLIDE_LO);     // 下のレール（左）
  box(g, 0.007, 0.014, SLIDE_LEN,  0.0455, SLIDE_BOT + 0.006, SLIDE_MIDZ, SLIDE_LO);     // 下のレール（右）
  box(g, 0.089, 0.082, 0.008, 0, SLIDE_MIDY, SLIDE_BACK - 0.003, SLIDE_LO);              // 後ろの面
  box(g, 0.032, 0.028, 0.006, 0, 0.052, SLIDE_BACK - 0.001, SLIDE_HI);                   // 撃針の蓋
  box(g, 0.091, 0.084, 0.012, 0, SLIDE_MIDY, SLIDE_FRONT + 0.006, SLIDE_HI);             // 前の面

  // ── 後ろのコッキングセレーション。両側に縦の溝を並べます ──
  for (let i = 0; i < 5; i++) {
    const z = -0.085 - i * 0.019;
    box(g, 0.005, 0.056, 0.008, -0.047, 0.055, z, SHADOW);
    box(g, 0.005, 0.056, 0.008,  0.047, 0.055, z, SHADOW);
  }

  // ── 銃口の上の四つの穴。18C の目印で、ここからガスが抜けて跳ね上がりを抑える ──
  // 掘り込みの底には、銃身側の切り欠きがのぞいています。
  box(g, 0.014, 0.014, 0.140, -0.0355, 0.091, -0.5545, SLIDE_HI);   // 穴の列の左ふち
  box(g, 0.014, 0.014, 0.140,  0.0355, 0.091, -0.5545, SLIDE_HI);   // 右ふち
  const portZ = [-0.502, -0.537, -0.572, -0.607];
  for (let i = 0; i < portZ.length; i++) {
    box(g, 0.057, 0.016, 0.024, 0, 0.090, portZ[i], SHADOW);   // 掘り込まれた穴
    box(g, 0.042, 0.012, 0.019, 0, 0.079, portZ[i], BARREL);   // 底にのぞく銃身
  }
  const bridgeZ = [-0.5195, -0.5545, -0.5895];
  for (let i = 0; i < bridgeZ.length; i++) {
    box(g, 0.060, 0.012, 0.012, 0, 0.092, bridgeZ[i], SLIDE);  // 穴と穴のあいだの橋
  }

  // ── 照星（前の照準）。頭が SIGHT_Y にぴたりと来るように ──
  box(g, 0.028, 0.010, 0.018, 0, SLIDE_TOP + 0.004, -0.641, SLIDE_LO);   // 台座
  box(g, 0.014, 0.024, 0.011, 0, SIGHT_Y - 0.012, -0.641, SLIDE_LO);     // 板（上端 = SIGHT_Y）
  box(g, 0.010, 0.010, 0.003, 0, SIGHT_Y - 0.011, -0.6468, WHITE);       // 白い点

  // ── 照門（後ろの照準）。まん中の U 字の切り欠きの両脇に白い点 ──
  box(g, 0.074, 0.012, 0.016, 0, SLIDE_TOP + 0.005, -0.075, SLIDE_LO);       // 台座
  box(g, 0.021, 0.026, 0.015, -0.0265, SIGHT_Y - 0.013, -0.075, SLIDE_LO);   // 左の柱（上端 = SIGHT_Y）
  box(g, 0.021, 0.026, 0.015,  0.0265, SIGHT_Y - 0.013, -0.075, SLIDE_LO);   // 右の柱
  box(g, 0.032, 0.017, 0.013, 0, SIGHT_Y - 0.017, -0.075, SHADOW);           // 切り欠きの底
  box(g, 0.008, 0.008, 0.003, -0.0265, SIGHT_Y - 0.013, -0.0677, WHITE);     // 白い点（左）
  box(g, 0.008, 0.008, 0.003,  0.0265, SIGHT_Y - 0.013, -0.0677, WHITE);     // 白い点（右）

  // ── 排莢口。右側に開いていて、中に薬室と銃身の張り出しが見えます ──
  box(g, 0.012, 0.044, 0.140, 0.0425, 0.072, -0.350, SHADOW);   // 掘り込み
  box(g, 0.016, 0.028, 0.092, 0.0355, 0.068, -0.332, BARREL);   // 薬室まわり
  box(g, 0.016, 0.007, 0.052, 0.0345, 0.083, -0.305, STEEL_D);  // 銃身の張り出しの天面
  box(g, 0.013, 0.007, 0.140, 0.0430, 0.052, -0.350, SLIDE_HI); // 口の下ぶち
  box(g, 0.009, 0.016, 0.030, 0.0465, 0.072, -0.276, STEEL);    // 排莢子（エキストラクター）

  // ── セレクター。後ろ右にある小さなレバーで、これが付くのは 18C だけ ──
  cyl(g, 0.017, 0.006, 0.049, 0.046, -0.066, STEEL_D, 'x');       // 丸い座
  box(g, 0.007, 0.036, 0.011, 0.052, 0.031, -0.060, STEEL, -20);  // レバーの腕
  box(g, 0.009, 0.010, 0.014, 0.053, 0.016, -0.049, STEEL);       // つまみ
  box(g, 0.004, 0.005, 0.005, 0.049, 0.060, -0.077, WHITE);       // 単発の目印
  box(g, 0.004, 0.005, 0.005, 0.049, 0.060, -0.055, WHITE);       // 連射の目印

  // ── フレーム後半。スライドを乗せる台と、手の水かきが当たるビーバーテイル ──
  box(g, 0.098, 0.055, 0.300, 0, -0.0275, -0.150, POLY);      // 受け側の胴
  box(g, 0.092, 0.014, 0.290, 0, 0.005, -0.150, POLY_HI);     // レールの段
  box(g, 0.088, 0.020, 0.055, 0, -0.010, -0.0275, POLY_HI);   // ビーバーテイル（上端が原点）
  box(g, 0.100, 0.100, 0.160, 0, -0.090, -0.085, POLY);       // 握りの付け根

  // ── ダストカバー。引き金より前、スライドの下にのびる樹脂の部分 ──
  box(g, 0.078, 0.055, 0.300, 0, -0.020, -0.452, POLY);
  box(g, 0.078, 0.056, 0.010, 0, -0.020, -0.597, POLY_HI);      // 前端の面
  box(g, 0.044, 0.014, 0.200, 0, -0.054, -0.460, POLY_HI);      // 下のアクセサリーレール
  box(g, 0.046, 0.016, 0.009, 0, -0.054, -0.430, SHADOW);       // レールの溝
  box(g, 0.005, 0.007, 0.260, -0.0400, -0.008, -0.452, SHADOW); // 左の合わせ目
  box(g, 0.005, 0.007, 0.260,  0.0400, -0.008, -0.452, SHADOW); // 右の合わせ目

  // ── 用心金（トリガーガード）。角ばっていて、前の下側が少しえぐれています ──
  box(g, 0.076, 0.118, 0.026, 0, -0.104, -0.301, POLY);       // 前の柱
  box(g, 0.076, 0.024, 0.162, 0, -0.164, -0.226, POLY);       // 下の橋
  box(g, 0.088, 0.042, 0.048, 0, -0.075, -0.150, POLY);       // 後ろの付け根
  box(g, 0.076, 0.020, 0.028, 0, -0.170, -0.297, POLY, -22);  // 前下のえぐり（アンダーカット）
  box(g, 0.078, 0.018, 0.030, 0, -0.056, -0.293, POLY_HI);    // 上の段
  box(g, 0.098, 0.090, 0.085, 0, -0.145, -0.1925, POLY);      // グリップ前面との継ぎ
  for (let i = 0; i < 2; i++) {
    box(g, 0.070, 0.007, 0.028, 0, -0.074 - i * 0.036, -0.3145, POLY_HI);  // 前面の滑り止め
  }

  // ── 引き金。まん中を縦に走る細い板がセーフアクションの安全レバー ──
  box(g, 0.020, 0.030, 0.012, 0, -0.066, -0.192, SHADOW);        // 付け根の影
  box(g, 0.017, 0.055, 0.015, 0, -0.088, -0.198, STEEL_D, -6);   // 引き金の本体
  box(g, 0.006, 0.046, 0.007, 0, -0.088, -0.2065, STEEL, -6);    // 安全レバーの板

  // ── 左側の操作部。分解レバー、スライドストップ、それとピン ──
  box(g, 0.008, 0.015, 0.042, -0.0480, -0.034, -0.246, STEEL_D); // 分解レバー（上半分）
  box(g, 0.009, 0.011, 0.030, -0.0490, -0.046, -0.246, STEEL);   // 分解レバー（つまみ）
  box(g, 0.007, 0.011, 0.086, -0.0490, -0.020, -0.292, STEEL_D); // スライドストップの腕
  box(g, 0.010, 0.017, 0.026, -0.0515, -0.023, -0.256, STEEL);   // 親指を掛ける所
  cyl(g, 0.007, 0.008, -0.0480, -0.041, -0.128, STEEL_D, 'x');   // 撃発機構のピン（左）
  cyl(g, 0.007, 0.008, -0.0480, -0.050, -0.176, STEEL_D, 'x');   // トリガーピン（左）
  cyl(g, 0.007, 0.008,  0.0480, -0.041, -0.128, STEEL_D, 'x');   // 同じピンの右側
  cyl(g, 0.007, 0.008,  0.0480, -0.050, -0.176, STEEL_D, 'x');

  // ── マガジンキャッチ。用心金のすぐ後ろにある押しボタン ──
  box(g, 0.013, 0.030, 0.022, -0.0505, -0.098, -0.196, POLY_HI);
  box(g, 0.006, 0.030, 0.024, -0.0545, -0.098, -0.196, SHADOW);  // 縁の影

  // ── グリップ。18 度後ろに寝ています。ここから下は傾いた座標で組みます ──
  gbox(g, 0.100, 0.368, 0.050, 0, -0.194, -0.030, POLY);      // バックストラップ
  gbox(g, 0.107, 0.223, 0.070, 0, -0.2665, -0.090, POLY);     // 握りの胴
  gbox(g, 0.098, 0.143, 0.045, 0, -0.3065, -0.1475, POLY);    // フロントストラップ側
  gbox(g, 0.104, 0.030, 0.100, 0, -0.372, -0.085, POLY_HI);   // 握りの底（弾倉の入り口）
  gbox(g, 0.086, 0.014, 0.086, 0, -0.368, -0.085, SHADOW);    // 弾倉の差込口

  // ── 握りの滑り止め。板の上に細かい粒を並べて表現します ──
  for (let s = -1; s <= 1; s += 2) {
    gbox(g, 0.006, 0.150, 0.080, s * 0.0545, -0.280, -0.095, POLY_HI);
    for (let r = 0; r < 2; r++) {
      for (let c = 0; c < 2; c++) {
        gbox(g, 0.004, 0.030, 0.026, s * 0.0575, -0.245 - r * 0.062, -0.072 - c * 0.042, POLY);
      }
    }
  }

  // ── フロントストラップの指かけ溝と、バックストラップの横筋 ──
  for (let i = 0; i < 3; i++) {
    gbox(g, 0.100, 0.014, 0.014, 0, -0.262 - i * 0.042, -0.170, POLY_HI);  // 出っぱり
    gbox(g, 0.096, 0.010, 0.010, 0, -0.283 - i * 0.042, -0.171, SHADOW);   // そのあいだの影
  }
  for (let i = 0; i < 2; i++) {
    gbox(g, 0.092, 0.010, 0.008, 0, -0.130 - i * 0.066, -0.004, POLY_HI);  // 背面の筋
  }

  // ── 33 連の延長マガジン。握りの下にずっと長く突き出た、あの棒 ──
  gbox(g, 0.084, 0.360, 0.115, 0, -0.530, -0.095, MAGBODY);       // 弾倉の胴
  gbox(g, 0.088, 0.340, 0.012, 0, -0.530, -0.156, MAGEDGE);       // 前の稜線
  gbox(g, 0.006, 0.340, 0.100, -0.0430, -0.530, -0.095, SHADOW);  // 左の合わせ目
  gbox(g, 0.006, 0.340, 0.100,  0.0430, -0.530, -0.095, SHADOW);  // 右の合わせ目
  for (let i = 0; i < 3; i++) {
    gbox(g, 0.005, 0.014, 0.014, 0.0445, -0.420 - i * 0.090, -0.095, SLIDE_LO); // 残弾の確認窓
  }
  gbox(g, 0.098, 0.012, 0.128, 0, -0.714, -0.095, POLY);      // 底板の受け
  gbox(g, 0.094, 0.030, 0.124, 0, -0.733, -0.095, POLY_HI);   // フロアプレート
  gbox(g, 0.096, 0.008, 0.128, 0, -0.746, -0.095, POLY);      // その底の縁

  // ── 銃口。銃身の穴と、その下に復座ばねの穴がのぞきます ──
  cyl(g, 0.023, 0.014, 0, BORE_Y, SLIDE_FRONT + 0.008, STEEL_D);    // 銃身の外まわり
  cyl(g, 0.019, 0.010, 0, BORE_Y, SLIDE_FRONT + 0.006, BARREL);     // その面
  cyl(g, 0.013, 0.010, 0, BORE_Y, SLIDE_FRONT + 0.005, SHADOW);     // 弾の出る穴
  cyl(g, 0.012, 0.010, 0, SPRING_Y, SLIDE_FRONT + 0.005, SHADOW);   // ばねの穴
  cyl(g, 0.006, 0.010, 0, SPRING_Y, SLIDE_FRONT + 0.006, STEEL);    // ガイドロッドの先

  // ── ゲームに渡す情報 ──
  g.userData.sightY = SIGHT_Y;                                     // 覗く高さ（照星・照門の頭）
  g.userData.muzzle = new THREE.Vector3(0, BORE_Y, SLIDE_FRONT);   // 弾の出る所

  return g;
}
