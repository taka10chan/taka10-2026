// ============================================================
//  Steyr AUG A1 ― ブルパップ式アサルトライフル
//
//  向き : 銃身は −Z を向く。+Y が上、+X が射手の右。
//  縮尺 : 1 単位 = 1 スタッド ≒ 0.28 m。
//         実銃の全長 790 mm ＝ 2.82 単位。
//         銃口 Z = −1.66、床尾板の後ろ端 Z = +1.16。差し引き 2.82。
//  原点 : 握りの「またぐら」（親指と人差し指の水かき）の所。
//         つまり握りの上後ろ、手のひらが機関部の下面に当たる点。
//         モデル全体はこの一点からぶら下がっている。
//
//  AUG の見分け方を、この順に作り込んである：
//    ・弾倉が握りより後ろ（ブルパップ）
//    ・オリーブの樹脂一体成形シェル
//    ・運搬把手そのものが 1.5 倍スコープ
//    ・手ぜんぶを包む巨大なミトン型用心金
//    ・銃身下の折りたたみ縦握り
// ============================================================

import * as THREE from '../../lib/three.module.js';

// ------------------------------------------------------------
//  材質は色ごとに一度だけ作って使い回す。
// ------------------------------------------------------------
const MAT = new Map();
function mat(hex) {
  let m = MAT.get(hex);
  if (!m) { m = new THREE.MeshLambertMaterial({ color: hex }); MAT.set(hex, m); }
  return m;
}

const OD     = 0x59614a;   // オリーブ樹脂。A1 の顔色
const ODLIT  = 0x6d7659;   // 光の当たる面
const ODDK   = 0x454c39;   // 影・彫り込み・パネルの合わせ目
const STEEL  = 0x1a1c21;   // 黒い鋼
const DARK   = 0x101216;   // もっと暗い所（穴・すき間）
const VOID   = 0x05060a;   // 穴の底
const WORN   = 0x6a6f78;   // 塗装のはげた金属
const GLASS  = 0x1c3b48;   // スコープの硝子（暗い青緑）
const RUBBER = 0x15171a;   // 床尾のゴム・アイカップ
const MAGB   = 0x7d8663;   // 半透明っぽい弾倉の樹脂
const MAGD   = 0x5c6449;   // 弾倉のワッフル模様の谷
const RED    = 0x8a2b22;   // 安全装置の赤点

// ------------------------------------------------------------
//  小道具。回転は「度」で書く。
// ------------------------------------------------------------

/** 箱をひとつ足す。 */
function box(g, w, h, d, x, y, z, hex, rx = 0, ry = 0, rz = 0) {
  const m = new THREE.Mesh(new THREE.BoxGeometry(w, h, d), mat(hex));
  m.position.set(x, y, z);
  if (rx || ry || rz) m.rotation.set(rx * Math.PI / 180, ry * Math.PI / 180, rz * Math.PI / 180);
  g.add(m);
  return m;
}

/** 薄い装飾板。パネルの合わせ目、すべり止めの筋、リブに使う。 */
function panel(g, w, h, d, x, y, z, hex, rx = 0) {
  return box(g, w, h, d, x, y, z, hex, rx);
}

/** 円柱。axis 'z' は銃身方向、'x' は左右、'y' は上下。 */
function cyl(g, r, len, x, y, z, hex, axis = 'z', seg = 10) {
  const m = new THREE.Mesh(new THREE.CylinderGeometry(r, r, len, seg), mat(hex));
  m.position.set(x, y, z);
  if (axis === 'z') m.rotation.x = Math.PI / 2;
  if (axis === 'x') m.rotation.z = Math.PI / 2;
  g.add(m);
  return m;
}

/** 前後で太さの違う円柱。rFront が −Z 側、rRear が +Z 側。 */
function cone(g, rFront, rRear, len, x, y, z, hex, seg = 12) {
  const m = new THREE.Mesh(new THREE.CylinderGeometry(rRear, rFront, len, seg), mat(hex));
  m.position.set(x, y, z);
  m.rotation.x = Math.PI / 2;
  g.add(m);
  return m;
}

// ------------------------------------------------------------
//  寸法の基準。ここだけ直せば全体がずれる。
// ------------------------------------------------------------
const BORE     = 0.26;    // 銃腔の高さ（原点＝手の水かきより上）
const SIGHT    = 0.52;    // 光学軸の高さ。銃腔より 73 mm 上、実銃どおり
const MUZZLE_Z = -1.66;   // 銃口
const HW       = 0.14;    // シェルの左右の半幅

export function build() {
  const g = new THREE.Group();

  // ==========================================================
  //  1. 樹脂シェル本体
  //     機関部・銃床・握り・用心金がぜんぶ地続きの一体成形。
  //     ここが AUG の「一本の塊」に見える所以。
  // ==========================================================
  box(g, HW * 2, 0.37, 1.74, 0, 0.165, 0.29, OD);          // 機関部＋銃床の胴
  box(g, 0.24, 0.04, 1.70, 0, 0.37, 0.29, ODLIT);          // 上面。少し明るい
  box(g, 0.26, 0.06, 0.62, 0, 0.40, 0.80, ODLIT);          // 頬付けの盛り上がり
  box(g, 0.26, 0.16, 0.62, 0, -0.09, 0.82, OD);            // 銃床の下腹
  box(g, 0.22, 0.24, 0.14, 0, BORE - 0.01, -0.63, OD);     // 前端。銃身の付け根
  panel(g, 0.18, 0.20, 0.05, 0, BORE, -0.71, ODDK);        // 前端の面取り

  // 左右の面に走る型合わせの筋。板を薄く浮かせて表現する。
  for (const s of [-1, 1]) {
    panel(g, 0.02, 0.03, 1.24, s * (HW + 0.005), 0.05, 0.33, ODDK);
    panel(g, 0.02, 0.03, 0.52, s * (HW + 0.005), 0.30, -0.28, ODDK);
    panel(g, 0.02, 0.14, 0.03, s * (HW + 0.005), 0.16, 0.62, ODDK);   // 縦の継ぎ目
  }

  // 成形時のねじ。小さい円柱を側面に埋める。
  for (const s of [-1, 1]) {
    cyl(g, 0.022, 0.02, s * (HW + 0.005), 0.08, 0.72, ODDK, 'x', 8);
  }

  // ==========================================================
  //  2. 床尾板。ゴムパッドと負い紐の環。
  // ==========================================================
  box(g, 0.29, 0.54, 0.05, 0, 0.14, 1.085, ODDK);          // 台座
  box(g, 0.26, 0.50, 0.06, 0, 0.14, 1.13, RUBBER);         // ゴムパッド
  for (const y of [0.28, 0.00]) {
    panel(g, 0.24, 0.025, 0.02, 0, y, 1.155, 0x24272c);    // 滑り止めの溝
  }
  for (const yy of [0.32, -0.04]) {
    cyl(g, 0.022, 0.02, 0.085, yy, 1.15, STEEL, 'z', 8);   // 留めねじ
  }
  box(g, 0.07, 0.06, 0.13, 0.105, -0.09, 1.00, STEEL);     // 負い紐の受け金
  cyl(g, 0.05, 0.03, 0.105, -0.11, 0.99, STEEL, 'x', 8);   // 環
  cyl(g, 0.028, 0.05, 0.105, -0.11, 0.99, VOID, 'x', 8);   // 環の穴

  // ==========================================================
  //  3. 弾倉。握りより後ろにあるのがブルパップの証拠。
  //     AUG の弾倉は半透明の樹脂で、側面にワッフル状の格子がある。
  // ==========================================================
  box(g, 0.24, 0.06, 0.42, 0, -0.05, 0.37, DARK);          // 弾倉挿入口の縁
  box(g, 0.22, 0.34, 0.38, 0, -0.20, 0.37, MAGB);          // 弾倉本体
  box(g, 0.24, 0.05, 0.40, 0, -0.395, 0.37, DARK);         // 底板

  // ワッフル模様。縦の骨と横の帯を薄板で示す。
  for (const s of [-1, 1]) {
    for (const z of [0.24, 0.33, 0.42, 0.51]) {
      panel(g, 0.02, 0.26, 0.045, s * 0.115, -0.20, z, MAGD);
    }
    panel(g, 0.02, 0.035, 0.34, s * 0.115, -0.10, 0.37, MAGD);
    panel(g, 0.02, 0.035, 0.34, s * 0.115, -0.30, 0.37, MAGD);
  }
  box(g, 0.06, 0.09, 0.05, 0.13, -0.08, 0.17, STEEL);      // 弾倉止めのレバー

  // ==========================================================
  //  4. 握り。原点はこの塊の上後ろの角。後ろへ 12 度倒してある。
  // ==========================================================
  box(g, 0.24, 0.44, 0.24, 0, -0.20, -0.08, OD, -12);      // 握りの胴
  panel(g, 0.20, 0.34, 0.05, 0, -0.20, -0.205, ODLIT, -12);// 前側の膨らみ
  panel(g, 0.20, 0.36, 0.05, 0, -0.20, 0.045, ODDK, -12);  // 後ろ側
  box(g, 0.22, 0.04, 0.22, 0, -0.42, -0.08, ODDK, -12);    // 底の蓋
  for (const s of [-1, 1]) {                               // 手が滑らないための筋
    for (const y of [-0.10, -0.18, -0.26, -0.34]) {
      panel(g, 0.02, 0.03, 0.22, s * 0.125, y, -0.08, ODDK, -12);
    }
  }

  // ==========================================================
  //  5. 巨大なミトン型用心金。
  //     指一本ぶんの輪ではなく、手ぜんぶを囲う。AUG の大きな特徴。
  // ==========================================================
  box(g, 0.24, 0.32, 0.05, 0, -0.175, -0.555, OD);         // 前の柱
  box(g, 0.24, 0.05, 0.44, 0, -0.355, -0.36, OD);          // 下の橋
  box(g, 0.24, 0.10, 0.10, 0, -0.31, -0.52, OD);           // 前下の面取り
  box(g, 0.24, 0.10, 0.10, 0, -0.31, -0.19, OD);           // 後ろ下の付け根
  panel(g, 0.25, 0.025, 0.40, 0, -0.335, -0.36, ODDK);     // 内側の影
  panel(g, 0.25, 0.28, 0.02, 0, -0.175, -0.578, ODDK);     // 前面の影
  box(g, 0.05, 0.15, 0.05, 0, -0.15, -0.32, STEEL, -8);    // 引き金
  box(g, 0.06, 0.05, 0.06, 0, -0.225, -0.31, DARK, -8);    // 引き金の靴
  cyl(g, 0.028, 0.30, 0, 0.04, -0.24, STEEL, 'x', 8);      // 横断式の安全装置
  cyl(g, 0.032, 0.02, -0.15, 0.04, -0.24, RED, 'x', 8);    // 撃てる側の赤点

  // ==========================================================
  //  6. 排莢口は右（+X）。真鍮をそらす小さな庇が付く。
  //     左側は同じ形の蓋で塞がれている（左右を入れ替えられる銃なので）。
  // ==========================================================
  panel(g, 0.025, 0.22, 0.38, HW + 0.005, 0.19, 0.13, ODDK);   // 右の枠
  panel(g, 0.02, 0.14, 0.30, HW + 0.02, 0.19, 0.13, DARK);     // 口の奥
  box(g, 0.06, 0.05, 0.13, HW + 0.03, 0.29, 0.27, ODLIT, 0, 0, -20); // 真鍮よけの庇
  panel(g, 0.025, 0.22, 0.38, -(HW + 0.005), 0.19, 0.13, ODDK);// 左は蓋
  panel(g, 0.02, 0.10, 0.26, -(HW + 0.018), 0.19, 0.13, ODDK); // 蓋の彫り

  // ==========================================================
  //  7. コッキングハンドルは左（−X）。前へ傾いた小さなつまみ。
  // ==========================================================
  panel(g, 0.02, 0.05, 0.42, -(HW + 0.005), 0.32, -0.32, DARK);// 走る溝
  box(g, 0.07, 0.06, 0.10, -0.17, 0.32, -0.38, STEEL);         // 腕
  box(g, 0.06, 0.17, 0.06, -0.195, 0.35, -0.40, STEEL, -18);   // つまみ
  box(g, 0.03, 0.07, 0.07, -(HW + 0.01), 0.18, -0.50, STEEL);  // 銃身取り外しの釦

  // ==========================================================
  //  8. 銃身・ガスブロック・消炎器。
  //     銃身はシェルの前から突き出し、先に穴あきの消炎器が付く。
  // ==========================================================
  cyl(g, 0.055, 0.80, 0, BORE, -1.08, STEEL);              // 銃身
  cyl(g, 0.058, 0.10, 0, BORE, -1.12, WORN);               // 塗装のはげた輪
  cyl(g, 0.048, 0.16, 0, BORE, -1.55, STEEL);              // 先の細い段
  cyl(g, 0.062, 0.04, 0, BORE, -0.70, WORN);               // 付け根の輪

  cyl(g, 0.082, 0.18, 0, BORE, -1.57, DARK, 'z', 12);      // 消炎器の胴
  panel(g, 0.04, 0.03, 0.14, 0, BORE + 0.082, -1.56, VOID);// 上の切り欠き
  panel(g, 0.04, 0.03, 0.14, 0, BORE - 0.082, -1.56, VOID);// 下
  panel(g, 0.03, 0.04, 0.14, -0.082, BORE, -1.56, VOID);   // 左
  panel(g, 0.03, 0.04, 0.14, 0.082, BORE, -1.56, VOID);    // 右
  cyl(g, 0.088, 0.03, 0, BORE, -1.645, STEEL, 'z', 12);    // 先端の輪 ＝ 銃口面
  cyl(g, 0.042, 0.02, 0, BORE, -1.652, VOID, 'z', 10);     // 弾の出る穴

  // 銃身の上のガスブロックとガス栓。
  box(g, 0.12, 0.13, 0.22, 0, BORE + 0.10, -0.76, STEEL);
  panel(g, 0.13, 0.03, 0.18, 0, BORE + 0.165, -0.76, DARK);
  cyl(g, 0.035, 0.12, 0, BORE + 0.10, -0.92, STEEL, 'z', 8);   // ガス筒
  cyl(g, 0.048, 0.05, 0, BORE + 0.10, -0.99, DARK, 'z', 8);    // ガス栓のつまみ
  box(g, 0.05, 0.06, 0.05, -0.09, BORE - 0.02, -0.70, STEEL);  // 前の負い紐環
  cyl(g, 0.038, 0.025, -0.105, BORE - 0.02, -0.70, STEEL, 'x', 8);

  // ==========================================================
  //  9. 折りたたみ式の縦前握り。少し前へ傾けてある。
  // ==========================================================
  box(g, 0.15, 0.14, 0.20, 0, BORE - 0.10, -0.84, DARK);       // 銃身に巻く帯
  cyl(g, 0.025, 0.18, 0, BORE - 0.12, -0.80, STEEL, 'x', 8);   // 蝶番の軸
  box(g, 0.11, 0.36, 0.13, 0, -0.02, -0.82, OD, 14);           // 握りの棒
  for (const y of [0.06, -0.04, -0.14]) {                      // 指掛かりの輪
    panel(g, 0.12, 0.03, 0.14, 0, y, -0.84, ODDK, 14);
  }
  box(g, 0.12, 0.04, 0.14, 0, -0.21, -0.87, ODDK, 14);         // 下の蓋

  // ==========================================================
  // 10. 運搬把手と一体の 1.5 倍スコープ。
  //     太い筒が機関部の上をほぼ全長にわたって走り、前だけ
  //     はっきり太い対物ベルになる。両端に硝子。下に短い支柱。
  //     筒そのものは水平のまま（傾けると sightY が嘘になる）、
  //     上の覆いだけ前下がりに倒して実銃の先すぼまりを出す。
  // ==========================================================
  cyl(g, 0.075, 1.04, 0, SIGHT, -0.10, STEEL, 'z', 12);        // スコープの筒
  box(g, 0.16, 0.06, 0.94, 0, SIGHT + 0.078, -0.06, OD, -2.5); // 把手として掴む覆い
  for (const z of [0.22, 0.10, -0.02, -0.14, -0.26]) {         // 滑り止めの刻み
    panel(g, 0.17, 0.03, 0.035, 0, SIGHT + 0.10, z, ODDK, -2.5);
  }
  panel(g, 0.17, 0.05, 0.03, 0, SIGHT + 0.075, 0.39, ODDK);    // 覆いの後ろ端

  cone(g, 0.115, 0.078, 0.16, 0, SIGHT, -0.62, STEEL);         // 対物側へ広がる肩
  cyl(g, 0.115, 0.17, 0, SIGHT, -0.785, STEEL, 'z', 12);       // 対物ベル
  panel(g, 0.24, 0.03, 0.14, 0, SIGHT + 0.115, -0.785, ODDK);  // ベル上の艶消し面
  cyl(g, 0.125, 0.03, 0, SIGHT, -0.885, DARK, 'z', 12);        // ベルの前輪
  cyl(g, 0.104, 0.02, 0, SIGHT, -0.878, GLASS, 'z', 12);       // 前の硝子

  cyl(g, 0.09, 0.10, 0, SIGHT, 0.45, STEEL, 'z', 12);          // 接眼部
  cyl(g, 0.10, 0.05, 0, SIGHT, 0.52, RUBBER, 'z', 12);         // ゴムのアイカップ
  cyl(g, 0.078, 0.02, 0, SIGHT, 0.535, GLASS, 'z', 12);        // 後ろの硝子
  cyl(g, 0.042, 0.05, -0.10, SIGHT, 0.02, DARK, 'x', 8);       // 零点調整のドラム
  cyl(g, 0.02, 0.02, -0.128, SIGHT, 0.02, ODLIT, 'x', 8);      // その頭

  // 機関部まで下ろす短い支柱。
  box(g, 0.09, 0.11, 0.13, 0, 0.40, 0.28, OD);
  box(g, 0.09, 0.11, 0.13, 0, 0.40, -0.34, OD);
  box(g, 0.09, 0.15, 0.11, 0, 0.40, -0.60, OD, -8);            // ベルを支える前脚
  cyl(g, 0.02, 0.10, 0, 0.40, 0.28, STEEL, 'x', 8);
  cyl(g, 0.02, 0.10, 0, 0.40, -0.34, STEEL, 'x', 8);

  // スコープが壊れた時のための、覆いに彫られた予備照準。
  box(g, 0.03, 0.05, 0.04, 0, SIGHT + 0.135, -0.44, ODDK);     // 前の柱
  for (const s of [-1, 1]) {
    box(g, 0.025, 0.045, 0.04, s * 0.035, SIGHT + 0.13, 0.32, ODDK); // 後ろの切り欠き
  }

  // ==========================================================
  //  覗く高さと銃口。ゲーム側がこの二つを使う。
  // ==========================================================
  g.userData.sightY = SIGHT;                                   // 光学軸の中心
  g.userData.muzzle = new THREE.Vector3(0, BORE, MUZZLE_Z);    // 火と曳光弾の出る所

  return g;
}
